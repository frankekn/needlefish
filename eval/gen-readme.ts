const EVAL_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.dirname(EVAL_DIR);

export const BENCHMARK_BEGIN = "<!-- benchmark:begin -->";
export const BENCHMARK_END = "<!-- benchmark:end -->";
export const GENERATED_NOTE =
  "<!-- generated by eval/gen-readme.ts from eval/leaderboard.json and eval/results/*.json — do not hand-edit -->";

function reportUrl(reportPath: string): string {
  return `${REPO_URL}/blob/main/eval/${reportPath}`;
}

function trim4(value: number): string {
  const trimmed = value.toFixed(4).replace(/0+$/, "");
  return trimmed.endsWith(".") ? `${trimmed}0` : trimmed;
}

export function gateMissedSummary(report: PublishedReport): string {
  const parts: string[] = [];
  const tierOne = tierRecall(report, 1);
  if (tierOne < 1) {
    const missed = Object.entries(report.fixtureTiers ?? {})
      .filter(([, tier]) => tier === 1)
      .map(([id]) => {
        const draws = report.results.filter((result) => result.fixtureId === id);
        return {
          id,
          hits: draws.filter((result) => result.score.recall).length,
          total: draws.length,
        };
      })
      .filter(({ hits, total }) => hits < total)
      .sort((a, b) => a.hits - b.hits || a.id.localeCompare(b.id))
      .map(({ id, hits, total }) => `\`${id}\` ${hits}/${total}`)
      .join(", ");
    parts.push(`Tier-1 ${(tierOne * 100).toFixed(2)}%: ${missed}`);
  }
  const noise = displayedMetrics(report).meanNoisePerPositive;
  if (noise > MAX_MEAN_NOISE_PER_POSITIVE) {
    parts.push(`noise ${trim4(noise)} > ${MAX_MEAN_NOISE_PER_POSITIVE}`);
  }
  if (parts.length === 0) {
    throw new Error("gate summary is only meaningful for disqualified lanes");
  }
  return parts.join("; ");
}

export function spliceBenchmarkBlock(
  source: string,
  block: string,
  file: string,
): string {
  const beginIdx = source.indexOf(BENCHMARK_BEGIN);
  const endIdx = source.indexOf(BENCHMARK_END);
  if (
    beginIdx === -1 ||
    endIdx === -1 ||
    endIdx < beginIdx ||
    source.indexOf(BENCHMARK_BEGIN, beginIdx + BENCHMARK_BEGIN.length) !== -1 ||
    source.indexOf(BENCHMARK_END, endIdx + BENCHMARK_END.length) !== -1
  ) {
    throw new Error(
      `${file}: expected exactly one ${BENCHMARK_BEGIN} / ${BENCHMARK_END} marker pair`,
    );
  }
  return (
    source.slice(0, beginIdx + BENCHMARK_BEGIN.length) +
    "\n" +
    block +
    source.slice(endIdx)
  );
}

export function renderBenchmarkBlock(
  manifest: LeaderboardManifest,
  configured: readonly Lane[],
  canonical: FixtureClassifications,
  locale: "en" | "zh-TW",
): string {
  const zh = locale === "zh-TW";
  const baseline = validateComparability(configured, manifest.baseline, canonical);
  const operational = configured.filter(
    ({ report }) => operationalFailures(report).length > 0,
  );
  const scored = configured.filter(
    ({ report }) => operationalFailures(report).length === 0,
  );
  const qualified = scored
    .filter(({ report }) => qualifies(report))
    .sort(compareLanes);
  const disqualified = scored
    .filter(({ report }) => !qualifies(report))
    .sort(compareLanes);
  if (qualified.length === 0) {
    throw new Error("no qualified lanes; refusing to publish an empty leaderboard");
  }
  for (const { config, report } of scored) {
    if (report.aggregates.cheatDetectedCount !== 0) {
      throw new Error(`${config.report}: cheatDetectedCount must be 0`);
    }
  }
  const deployment = configured.find(({ config }) => config.status === "Deployed");
  const fixtureCount = baseline.report.fixtures?.length;
  if (fixtureCount === undefined || !baseline.report.gitSha) {
    throw new Error("baseline report must list its fixtures and git SHA");
  }
  const measured = baseline.report.createdAt.slice(0, 10);
  const gitSha7 = baseline.report.gitSha.slice(0, 7);
  const holdoutText =
    baseline.report.holdout === "include"
      ? zh
        ? "包含 sealed holdout"
        : "sealed holdouts included"
      : zh
        ? `holdout ${baseline.report.holdout}`
        : `holdouts ${baseline.report.holdout}`;

  const provenance = zh
    ? `**更新於 ${manifest.updated}**——量測於 ${measured}；全部 ${configured.length} 條公開 lane 各跑 ${fixtureCount} 個情境 × ${baseline.report.draws} 次，${holdoutText}，Class ${baseline.report.gateClass} gate，anti-cheat v${baseline.report.anticheatVersion}；commit \`${gitSha7}\`，prompt \`${baseline.report.promptHash}\`，fixture set \`${baseline.report.fixtureSetHash}\`，scorer \`${baseline.report.scorerHash}\`；每份 report 皆為 \`cheatDetectedCount: 0\`。`
    : `**Updated ${manifest.updated}** — measured ${measured}; all ${configured.length} published lanes at ${fixtureCount} scenarios × ${baseline.report.draws} draws, ${holdoutText}, Class ${baseline.report.gateClass} gate, anti-cheat v${baseline.report.anticheatVersion}; commit \`${gitSha7}\`, prompt \`${baseline.report.promptHash}\`, fixture set \`${baseline.report.fixtureSetHash}\`, scorer \`${baseline.report.scorerHash}\`; every report has \`cheatDetectedCount: 0\`.`;

  const rankedIntro = deployment
    ? zh
      ? `**排名 lane。** **目前部署 lane：${deployment.config.name}（\`${deployment.report.model}\` @ \`${deployment.report.effort}\`）**（${manifest.updated} 選定）——hosted action 與 reusable workflow 的預設。粗體標示目前部署的 lane 與每欄最佳值。`
      : `**Ranked lanes.** **Deployed lane: ${deployment.config.name} (\`${deployment.report.model}\` at \`${deployment.report.effort}\` effort)** (selected ${manifest.updated}) — what the hosted action and reusable workflow run by default. Bold marks the deployed lane and the best value in each column.`
    : zh
      ? "**排名 lane。** 粗體標示每欄最佳值。"
      : "**Ranked lanes.** Bold marks the best value in each column.";

  const rows = qualified.map((lane) => {
    const metrics = displayedMetrics(lane.report);
    return {
      lane,
      balanced: balancedReviewAccuracy(lane.report),
      ci: scoreConfidenceInterval(lane.report),
      tierOne: tierRecall(lane.report, 1),
      falsePositiveRate: metrics.falsePositiveRate,
      noise: metrics.meanNoisePerPositive,
      meanDurationMs: metrics.meanDurationMs,
    };
  });
  const uniqueExtremum = (
    values: readonly number[],
    value: number,
    direction: "max" | "min",
  ): boolean => {
    const best = direction === "max" ? Math.max(...values) : Math.min(...values);
    return value === best && values.filter((item) => item === best).length === 1;
  };
  const bold = (text: string, values: readonly number[], value: number, direction: "max" | "min"): string =>
    uniqueExtremum(values, value, direction) ? `**${text}**` : text;
  const balancedValues = rows.map((row) => row.balanced);
  const tierOneValues = rows.map((row) => row.tierOne);
  const fpValues = rows.map((row) => row.falsePositiveRate);
  const noiseValues = rows.map((row) => row.noise);
  const meanValues = rows.map((row) => row.meanDurationMs);
  const ranks = statisticalRanks(qualified);
  const rankedHeader = zh
    ? "| 名次 | Lane | Harness | Effort | Balanced | 95% CI | Tier-1 | FP | Noise/review | 平均 |"
    : "| Rank | Lane | Harness | Effort | Balanced | 95% CI | Tier-1 | FP | Noise/review | Mean |";
  const rankedTable = [
    rankedHeader,
    "| ---: | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...rows.map((row, index) => {
      const { config, report } = row.lane;
      const url = reportUrl(config.report);
      const laneCell =
        deployment !== undefined && config === deployment.config
          ? zh
            ? `**[${config.name}](${url})（目前部署）**`
            : `**[${config.name}](${url}) (deployed)**`
          : `[${config.name}](${url})`;
      const [lower, upper] = row.ci;
      const cells = [
        String(ranks[index]),
        laneCell,
        report.runnerVersion ?? "",
        report.effort,
        bold(`${(row.balanced * 100).toFixed(2)}%`, balancedValues, row.balanced, "max"),
        `${(lower * 100).toFixed(1)}%–${(upper * 100).toFixed(1)}%`,
        bold(`${(row.tierOne * 100).toFixed(0)}%`, tierOneValues, row.tierOne, "max"),
        bold(`${(row.falsePositiveRate * 100).toFixed(2)}%`, fpValues, row.falsePositiveRate, "min"),
        bold(row.noise.toFixed(3), noiseValues, row.noise, "min"),
        bold(`${Math.round(row.meanDurationMs / 1000)}s`, meanValues, row.meanDurationMs, "min"),
      ];
      return `| ${cells.join(" | ")} |`;
    }),
  ].join("\n");

  const unrankedIntro = zh
    ? `**未排名 lane**，同批量測——目前 interim gate 要求 Tier-1 共 21 draws 至少成功 20 次、每個 fixture 至少 2/3，且 positive noise 不超過 ${MAX_MEAN_NOISE_PER_POSITIVE}；事後 x3 確認僅作記錄，不恢復名次。`
    : `**Unranked lanes**, same run — the interim gate requires at least 20/21 Tier-1 successes, at least 2/3 on every fixture, and positive noise no higher than ${MAX_MEAN_NOISE_PER_POSITIVE}; a later x3 confirmation is recorded but does not restore the rank.`;

  const sections = [GENERATED_NOTE, provenance, rankedIntro, rankedTable, unrankedIntro];
  if (disqualified.length > 0) {
    const unrankedHeader = zh
      ? "| Lane | Balanced | 完整報告未過的門檻 |"
      : "| Lane | Balanced | Gate missed in the full report |";
    sections.push(
      [
        unrankedHeader,
        "| --- | ---: | --- |",
        ...disqualified.map(
          ({ config, report }) =>
            `| [${config.name}](${reportUrl(config.report)}) ${report.effort} | ${(balancedReviewAccuracy(report) * 100).toFixed(2)}% | ${gateMissedSummary(report)} |`,
        ),
      ].join("\n"),
    );
  }
  if (operational.length > 0) {
    sections.push(
      zh
        ? `${operational.length} 條 lane 因 provider 或基礎設施故障而不計分；詳見 benchmark 頁面與 eval/RESULTS.md。`
        : `${operational.length} lane(s) had provider or infrastructure failures and are excluded from scoring; see the benchmark page and eval/RESULTS.md.`,
    );
  }
  return sections.join("\n\n") + "\n";
}

const isMain =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const manifest = readManifest();
  validateExcludedReportFiles(manifest);
  const lanes = manifest.lanes.map(readLane);
  const canonical = fixtureClassifications(await loadFixtures(null));
  for (const [file, locale] of [
    ["README.md", "en"],
    ["README.zh-TW.md", "zh-TW"],
  ] as const) {
    const abs = path.join(REPO_ROOT, file);
    const updated = spliceBenchmarkBlock(
      readFileSync(abs, "utf8"),
      renderBenchmarkBlock(manifest, lanes, canonical, locale),
      file,
    );
    writeFileSync(abs, updated);
  }
  process.stderr.write(
    `updated README.md, README.zh-TW.md (${lanes.length} lanes)\n`,
  );
}
